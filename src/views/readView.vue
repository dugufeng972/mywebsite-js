        </p>
        <p>
          如此数日，这只大老鼠每天都来同胡国华一起吸烟，胡国华到处被人轻贱，周围没有半个朋友，对这只老鼠惺惺相惜颇有好感，有时候老鼠来得晚一点，胡国华就忍着烟瘾等它。
        </p>
        <p>
          但是好景不长，胡国华家里就剩下一张床和四面墙了，再也没有钱去买烟土，他愁闷无策，叹息的对老鼠说：“老鼠啊老鼠，今天我囊謦粮绝，可再没钱买福寿膏了，恐不能与你常吸此味。”言毕唏嘘不已。
        </p>
